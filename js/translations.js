// =====================================================
// LANGUAGE CONTROL
// =====================================================


let currentLanguage =
    localStorage.getItem("language") || "en";





function changeLanguage(lang) {


    currentLanguage = lang;



    localStorage.setItem(
        "language",
        lang
    );



    // TEXT CHANGE

    document
        .querySelectorAll("[data-key]")
        .forEach(element => {


            let key =
                element.getAttribute("data-key");



            if (
                translations[lang] &&
                translations[lang][key]
            ) {

                element.innerHTML =
                    translations[lang][key];

            }



        });




    // PLACEHOLDER CHANGE

    document
        .querySelectorAll("[data-placeholder]")
        .forEach(element => {


            let key =
                element.getAttribute("data-placeholder");



            if (
                translations[lang] &&
                translations[lang][key]
            ) {

                element.placeholder =
                    translations[lang][key];

            }



        });




    // Reload crop cards

    if (typeof displayCrops === "function") {

        displayCrops();

    }



}





// AUTO LOAD LANGUAGE


window.addEventListener(
    "DOMContentLoaded",
    () => {


        changeLanguage(currentLanguage);


    });